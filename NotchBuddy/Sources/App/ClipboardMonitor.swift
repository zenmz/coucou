import Foundation
import AppKit

// MARK: - ClipboardMonitor

final class ClipboardMonitor: @unchecked Sendable {
    static let shared = ClipboardMonitor()

    private var timer: Timer?
    private var lastChangeCount: Int = NSPasteboard.general.changeCount
    private var isStarted = false

    // Known transient/concealed pasteboard types to ignore
    private static let ignoredTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword")
    ]

    // Known sensitive / password manager app bundle IDs to ignore
    private static let ignoredBundleIDs: Set<String> = [
        "com.agilebits.onepassword",
        "com.agilebits.onepassword7",
        "com.bitwarden.desktop",
        "com.apple.keychainaccess",
        "org.keepassxc.keepassxc",
        "com.lastpass.LastPass",
        "com.nordpass.macos",
        "com.enpass.Enpass"
    ]

    private init() {}

    func start() {
        guard !isStarted else { return }
        isStarted = true
        lastChangeCount = NSPasteboard.general.changeCount

        let t = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in
            self?.checkPasteboard()
        }
        t.tolerance = 0.1
        RunLoop.main.add(t, forMode: .common)
        self.timer = t
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        isStarted = false
    }

    private func checkPasteboard() {
        let board = NSPasteboard.general
        let currentCount = board.changeCount
        guard currentCount != lastChangeCount else { return }
        lastChangeCount = currentCount

        // 1. Check for transient or concealed metadata types
        if let types = board.types {
            for ignored in Self.ignoredTypes {
                if types.contains(ignored) { return }
            }
        }

        // 2. Check frontmost application (exclude password managers)
        let frontApp = NSWorkspace.shared.frontmostApplication
        let bundleID = frontApp?.bundleIdentifier ?? ""
        if Self.ignoredBundleIDs.contains(bundleID) { return }

        // 3. Extract text
        guard let text = board.string(forType: .string) else { return }
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return }

        let appName = frontApp?.localizedName ?? bundleID

        MainActor.assumeIsolated {
            ClipboardStore.shared.add(text, sourceApp: appName)
        }
    }
}
